#!/usr/bin/env python3
"""Refuse a file too large for one reading.

Budget: 5,000 tokens per file, estimated as `bytes / 4`. The estimate is crude
and deliberate — it needs no tokenizer, so it cannot disagree with itself
between machines, and it is close enough for the only claim it makes: a file
this size is no longer a file an agent or a reviewer reads in one pass.

    python3 scripts/check_file_size.py          # staged files (pre-commit)
    python3 scripts/check_file_size.py --all    # every tracked file (CI)
    python3 scripts/check_file_size.py a b c    # explicit paths (debugging)

Scope is the staged set on purpose: a repo-wide run in a commit hook fails on
pre-existing drift and teaches everyone `--no-verify`. Sizes come from the index
(`git cat-file -s :path`), so a file staged at one size and edited after another
is judged as it will be committed.

Generated files are not the author's problem and are skipped: lockfiles,
minified bundles, sourcemaps, protobuf output, vendored trees, build output.
Anything else that genuinely cannot be split is exempted by adding its glob to
`.file-size-ignore` with a comment saying why — an exemption is a reviewed line
in the repo, not a missing check.

Exit codes: 0 within budget, 1 over budget, 2 bad invocation.
"""

from __future__ import annotations

import fnmatch
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

MAX_TOKENS = 5_000
BYTES_PER_TOKEN = 4
MAX_BYTES = MAX_TOKENS * BYTES_PER_TOKEN

EXEMPT_FILE = ".file-size-ignore"

# Whole trees that are generated, vendored, or not ours to read.
SKIP_PARTS = frozenset(
    {
        ".git", ".agents", "node_modules", ".venv", "venv", "__pycache__",
        ".pytest_cache", ".mypy_cache", "dist", "build", "out", "target",
        ".next", ".turbo", ".astro", ".svelte-kit", ".nuxt", ".output",
        ".vercel", ".netlify", ".parcel-cache", ".wrangler", "storybook-static",
        "coverage", "vendor", "third_party", "__snapshots__",
    }
)

# Generated by a tool, never edited by hand.
SKIP_GLOBS = (
    "*.lock", "*.lockb", "bun.lock", "package-lock.json", "pnpm-lock.yaml",
    "yarn.lock", "uv.lock", "Cargo.lock", "poetry.lock", "composer.lock",
    "Gemfile.lock", "skills-lock.json",
    "*.min.js", "*.min.css", "*.map", "*.bundle.js",
    "*.pb.go", "*_pb2.py", "*_pb2_grpc.py", "*.g.dart", "*.freezed.dart",
    "*.generated.*", "*.designer.cs", "*.snap",
)


def git(*args: str, cwd: Path | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(
        ("git",) + args,
        cwd=cwd or REPO,
        capture_output=True,
        text=True,
    )


def repo_root() -> Path:
    r = git("rev-parse", "--show-toplevel")
    return Path(r.stdout.strip()) if r.returncode == 0 and r.stdout.strip() else REPO


def staged_paths(root: Path) -> list[str]:
    """Added, copied, modified or renamed in the index; deletions are skipped."""
    r = git("diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z", cwd=root)
    return [p for p in r.stdout.split("\0") if p]


def tracked_paths(root: Path) -> list[str]:
    r = git("ls-files", "-z", cwd=root)
    return [p for p in r.stdout.split("\0") if p]


def staged_size(root: Path, rel: str) -> int | None:
    """Size of the blob in the index, not the working tree."""
    r = git("cat-file", "-s", ":" + rel, cwd=root)
    if r.returncode == 0 and r.stdout.strip().isdigit():
        return int(r.stdout.strip())
    return None


def is_binary(root: Path, rel: str) -> bool:
    p = root / rel
    try:
        with p.open("rb") as fh:
            return b"\0" in fh.read(8000)
    except OSError:
        return False


def exemptions(root: Path) -> list[str]:
    p = root / EXEMPT_FILE
    if not p.is_file():
        return []
    out = []
    for raw in p.read_text(errors="replace").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def exempt(rel: str, patterns: list[str]) -> bool:
    parts = Path(rel).parts
    if any(part in SKIP_PARTS for part in parts):
        return True
    name = parts[-1] if parts else rel
    if any(fnmatch.fnmatch(name, g) or fnmatch.fnmatch(rel, g) for g in SKIP_GLOBS):
        return True
    return any(
        fnmatch.fnmatch(rel, p) or fnmatch.fnmatch(name, p)
        for p in patterns
    )


def tokens(size: int) -> int:
    return (size + BYTES_PER_TOKEN - 1) // BYTES_PER_TOKEN


def report(root: Path, over: list[tuple[str, int]], checked: int, skipped: int) -> int:
    print(
        f"File-size gate: {checked} file(s) measured, {skipped} skipped "
        f"(generated or exempt). Budget {MAX_TOKENS:,} tokens = {MAX_BYTES:,} bytes."
    )
    if not over:
        print("ok — every measured file is within budget.")
        return 0

    over.sort(key=lambda item: item[1], reverse=True)
    print()
    print(f"{len(over)} file(s) over the {MAX_TOKENS:,}-token budget (bytes / {BYTES_PER_TOKEN}):")
    print()
    for rel, size in over:
        print(
            f"  {rel}  {size:,} B  ≈{tokens(size):,} tokens  "
            f"({tokens(size) - MAX_TOKENS:,} over)"
        )
    print()
    print("Commit refused. Split the file; do not raise the budget.")
    print()
    print("How to split it")
    print("  1. Find the seams, don't guess them:")
    print("       markdown   grep -n '^## ' FILE")
    print("       python     grep -nE '^(def|class|# ──)' FILE")
    print("       ts/js      grep -nE '^(export |function |class |// ──)' FILE")
    print("  2. Move one seam's worth of content into its own file, named for that seam.")
    print("       a skill      topics/<seam>.md, one pointer line left in SKILL.md")
    print("       a module     <package>/<seam>.py, imported by the file it left")
    print("       a component  components/<seam>.tsx, imported by its former parent")
    print("  3. Leave a one-line pointer at the old location, so nothing links to a dead path.")
    print("  4. Re-run this gate, then re-stage: `git add -A`.")
    print("  5. Only if the file is generated or genuinely atomic, exempt it:")
    print(f"       echo 'PATH_OR_GLOB  # why this cannot be split' >> {EXEMPT_FILE}")
    print()
    print("A single file over this budget is a file nobody finishes reading.")
    return 1


def main(argv: list[str]) -> int:
    root = repo_root()

    if argv and argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0

    whole_index = "--all" in argv
    explicit = [a for a in argv if not a.startswith("-")]
    unknown = [a for a in argv if a.startswith("-") and a not in ("--all",)]
    if unknown:
        print(f"unknown flag(s): {' '.join(unknown)}", file=sys.stderr)
        return 2

    if explicit:
        paths, sizes = list(explicit), None
    elif whole_index:
        paths, sizes = tracked_paths(root), None
    else:
        paths, sizes = staged_paths(root), staged_size
    if not paths:
        print("File-size gate: nothing staged, so nothing to measure.")
        return 0

    patterns = exemptions(root)
    over: list[tuple[str, int]] = []
    checked = skipped = 0

    for rel in paths:
        if not rel:
            continue
        if exempt(rel, patterns):
            skipped += 1
            continue
        size = sizes(root, rel) if sizes else None
        if size is None:
            try:
                size = (root / rel).stat().st_size
            except OSError:
                skipped += 1
                continue
        if is_binary(root, rel):
            skipped += 1
            continue
        checked += 1
        if size > MAX_BYTES:
            over.append((rel, size))

    return report(root, over, checked, skipped)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
